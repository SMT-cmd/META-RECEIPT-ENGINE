const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const ui=fs.readFileSync(path.resolve(__dirname,'../platform/worker/client.js'),'utf8');
test('GWS connection visible to authorized business owners from overview and navigation',()=>{
 assert.match(ui,/data-nav="gws"><strong>⇆ Connect Global Webstores/);
 assert.match(ui,/const primary=\['overview','documents','create','customers','products','payments','gws'\]/);
 assert.match(ui,/if\(v==='team'\|\|v==='branding'\|\|v==='design'\|\|v==='gws'/);
});
test('a GWS vendor can follow a deep link straight to the Bizlano connection code',()=>{
 assert.match(ui,/new URL\(location.href\).searchParams.get\('connect'\)==='gws'&&admin\(\)/);
 assert.match(ui,/state.view='gws'/);
 assert.match(ui,/await load\(\)/);
 assert.match(ui,/Open GWS connection screen/);
 assert.match(ui,/Continue to GWS/);
 assert.match(ui,/Copy connection code/);
 assert.doesNotMatch(ui,/\?code=\$\{/);
});
test('link code is still generated by authorized backend and not embedded in a URL',()=>{
 assert.match(ui,/api\('\/b\/'\+state.biz.slug\+'\/marketplace',\{action:'link'\}\)/);
 assert.match(ui,/result.expiresInMinutes/);
});
